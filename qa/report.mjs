// Renders qa/results/raw.jsonl (written by real-world.spec.ts) into docs/QA_REPORT.md.
// Every row comes from an executed scenario; nothing here is typed by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const raw = new URL('./results/raw.jsonl', import.meta.url)
if (!existsSync(raw)) { console.error('No QA results; run `npm run qa` first.'); process.exit(1) }
const rows = readFileSync(raw, 'utf8').trim().split('\n').map((l) => JSON.parse(l))
const env = JSON.parse(readFileSync(new URL('./results/env.json', import.meta.url), 'utf8'))
const fmtMs = (ms) => (ms == null ? '—' : ms < 1000 ? `${ms} ms` : `${(ms / 1000).toFixed(1)} s`)
const fmtB = (b) => (b == null ? '—' : b < 1048576 ? `${(b / 1024).toFixed(0)} KB` : `${(b / 1048576).toFixed(1)} MB`)
const esc = (s) => String(s).replace(/\|/g, '\\|')
const pass = rows.filter((r) => r.status === 'PASS').length

let md = `# FreePDF real-world QA report

_Generated by \`npm run qa\` (qa/real-world.spec.ts → qa/report.mjs). Every row below was executed; results are not edited by hand._

## Environment

| | |
|---|---|
| Date | ${env.date} |
| Browser | ${env.browser} |
| Server | ${env.server} |
| Machine | ${env.cpu}, ${env.ram} RAM, ${env.platform} |
| Node | ${env.node} |
| Validators | qpdf --check, pypdf (strict mode), pyHanko (signatures); network checked against the privacy-guard rules on every request |

**Result: ${pass} of ${rows.length} scenarios passed.**

`
const cats = [...new Set(rows.map((r) => r.category))]
for (const c of cats) {
  md += `## ${c}\n\n| ID | Input | Operation | Expected | Actual | Time | Output | Status |\n|---|---|---|---|---|---|---|---|\n`
  for (const r of rows.filter((x) => x.category === c)) {
    md += `| ${r.id} | ${esc(r.input)} | ${esc(r.operation)} | ${esc(r.expected)} | ${esc(r.actual)} | ${fmtMs(r.ms)} | ${fmtB(r.outBytes)} | ${r.status === 'PASS' ? '✅ PASS' : '❌ FAIL'} |\n`
  }
  md += '\n'
}
md += `## Not executed in this environment

| Area | Status | Why / what to do |
|---|---|---|
| This QA suite in Firefox / WebKit | **Not executed** | The QA suite runs on desktop Chromium only. Firefox and WebKit are covered by the browser suite in CI's \`cross-engine\` job and by \`qa/webkitgtk-smoke.mjs\` (see docs/TESTING.md). |
| Physical Android / iOS devices | **Not executed** | No hardware is available. Device projects in the automated suite are Chromium **emulations** (viewport, touch, DPR, UA). Manual steps: docs/RELEASE_CHECKLIST.md. |
| Real low-memory termination (OS killing a tab) | **Not executed** | Approximated by refusing over-limit files on a device reporting 2 GB, and by a simulated worker crash (automated suite). |
`
writeFileSync(new URL('../docs/QA_REPORT.md', import.meta.url), md)
console.log(`QA report: ${pass}/${rows.length} passed → docs/QA_REPORT.md`)
if (process.argv.includes('--strict') && (rows.length === 0 || pass !== rows.length)) {
  // A scenario that never ran is caught by Playwright's own exit code (qa/run.mjs combines both).
  console.error(`QA FAILED: ${rows.length - pass} of ${rows.length} recorded scenarios did not pass.`)
  process.exit(1)
}
